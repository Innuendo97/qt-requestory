def test_sixty_pages_under_budget():
    """Review Focus 5: 60 pages, ~40 blocks a page, comparison under 10 s."""
    blocks = []
    for k in range(2400):
        if k % 25 == 0:
            blocks.append(ROW)
        elif k % 7 == 0:
            blocks.append(f"{pdfgen.lorem(8, seed=k)} il 0{1 + k % 9}/02/2026 importo € {k},00")
        else:
            blocks.append(pdfgen.lorem(8 + k % 5, seed=k))
    generated = []
    for k, text in enumerate(blocks):
        if k % 97 == 5:
            continue                                   # missing block
        if text == ROW:
            text = f"Nome Anna{k} Cognome Neri{k}"
        elif "/02/2026" in text:
            text = text.replace("/02/", "/03/").replace(f"€ {k},00", f"€ {k + 1},00")
        elif k % 13 == 0:
            text = text.replace(text.split()[1], "cambiata", 1)
        generated.append(text)
        if k % 150 == 7:
            generated.append(pdfgen.lorem(10, seed=10_000 + k))   # extra block
    target = _doc(*blocks, lines_per_page=80)
    other = _doc(*generated, lines_per_page=80)
    assert len(target.page_sizes) >= 60
    started = time.perf_counter()
    result = compare_docs(target, other, rules=ON)
    elapsed = time.perf_counter() - started
    log.warning("sixty pages: compare_docs in %.2f s", elapsed)
    print(f"\nsixty pages: compare_docs in {elapsed:.2f} s ({len(result.diffs)} differences)")
    assert elapsed < 10, f"60 pages took {elapsed:.2f} s"
    klasses = {d.klass for d in result.diffs}
    assert {"variabile", "testo", "rumore"} <= klasses
    assert not [d for d in result.diffs if d.op == "spostato"]
    assert sum(1 for d in result.diffs if d.klass == "variabile") == 2 * sum(1 for t in generated if "Anna" in t)


