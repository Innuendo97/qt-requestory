def test_noise_rules_make_dates_rumore_and_bad_rules_are_noted():
    target = _doc("Documento emesso il 01/02/2026. Pagina di prova.")
    generated = _doc("Documento emesso il 1 febbraio 2026. Pagina di prova.")
    assert _summary(compare_docs(target, generated)) == [("cambiato", "testo")]
    rules = [*PRESETS[:2], NoiseRule("Data", r"\d{2}/\d{2}/\d{4}", True), NoiseRule("Rotta", "(", True)]
    rules[1] = NoiseRule(PRESETS[1].name, PRESETS[1].pattern, True)
    result = compare_docs(target, generated, rules=rules)
    assert _summary(result) == [("cambiato", "rumore")]
    assert result.diffs[0].left_text == "01/02/2026." and result.diffs[0].right_text == "1 febbraio 2026."
    assert result.noise_hits == (("Data", 2),)
    assert "regola «Rotta» ignorata: espressione non valida" in result.note
    assert "regola «Data» ignorata: nome già usato" in result.note


