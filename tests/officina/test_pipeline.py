# ------------------------------------ HTML without boxes: block ends are line ends (final review I1) ---

def _boxed(html: str) -> tuple[Block, ...]:
    """The blocks of ``html`` with synthetic boxes: one printed line per block."""
    out = []
    for b, block in enumerate(_html_blocks(html)):
        words = tuple(replace(w, page=0, x0=10 + 40 * k, x1=40 + 40 * k, y0=20 * b, y1=20 * b + 10)
                      for k, w in enumerate(block.words))
        out.append(replace(block, words=words))
    return tuple(out)


@pytest.mark.parametrize("boxes", [False, True], ids=["no boxes", "boxes"])
def test_a_label_alone_in_its_block_is_a_probable_slot_without_boxes_too(boxes: bool):
    make = _boxed if boxes else _html_blocks
    target = make("<p>Riferimento:</p><p>Gentile cliente, la informiamo</p>")
    tobe = make("<p>Riferimento: il contratto scade</p><p>Gentile cliente, la informiamo</p>")
    result = compare_docs(target, tobe)
    assert _summary(result) == [("cambiato", "variabile")] and result.slots_found == 1
    assert result.diffs[0].right_text == "il contratto scade"


@pytest.mark.parametrize("boxes", [False, True], ids=["no boxes", "boxes"])
def test_a_sure_slot_never_swallows_an_inserted_paragraph_without_boxes(boxes: bool):
    make = _boxed if boxes else _html_blocks
    target = make("<p>Nome ..........</p><p>Il canone mensile resta invariato per un anno</p>"
                  "<p>Coda comune finale del documento</p>")
    tobe = make("<p>Nome Mario</p><p>Premessa aggiuntiva non prevista dal cliente</p>"
                "<p>Il canone mensile resta invariato per un anno</p><p>Coda comune finale del documento</p>")
    result = compare_docs(target, tobe)
    assert [(d.op, d.klass, d.right_text) for d in result.diffs] == [
        ("cambiato", "variabile", "Mario"),
        ("in_piu", "testo", "Premessa aggiuntiva non prevista dal cliente")]
