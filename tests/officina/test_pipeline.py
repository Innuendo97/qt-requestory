@pytest.mark.parametrize("neighbour", ["next_word", "previous_word"])
def test_a_missing_section_next_to_a_change_is_one_section_and_one_change(neighbour: str):
    """R27: an unmatched target block is a hard boundary of the word diff."""
    intro, price = "Premessa del contratto di prova tra le parti.", "Il prezzo resta fisso per dodici mesi."
