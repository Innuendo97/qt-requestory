def _doc(*paragraphs: str, pages: int = 1, lines_per_page: int = 48, size: float = 11.0) -> DocText:
    """Paragraphs laid out on lines of ≤ 12 words, 14 pt apart, a blank line
    between paragraphs, a new page every ``lines_per_page`` lines."""
    words: list[Word] = []
    line = 0
    for paragraph in paragraphs:
        tokens = paragraph.split()
        for start in range(0, len(tokens), 12):
            page, row = divmod(line, lines_per_page)
            y, x = 50.0 + 14.0 * row, 40.0
            for token in tokens[start:start + 12]:
                words.append(Word(token, page, x, y, x + 5.0 * len(token), y + 11.0, size))
                x += 5.0 * (len(token) + 1)
            line += 1
        line += 1
    pages = max(pages, (words[-1].page + 1) if words else 1)
    return DocText(words, [(595.0, 842.0)] * pages, bool(words))


