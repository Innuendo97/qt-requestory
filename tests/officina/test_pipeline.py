# ------------------------------------------------------ HTML links (E7) ---

def _html_blocks(html: str):
    from qtrequestory.officina.compare.extract_html import extract_html

    return extract_html(html.encode())[0]


def test_a_changed_href_is_one_link_diff_that_counts():
    target = _html_blocks('<body><p>Leggi le <a href="https://example.invalid/a">condizioni</a> ora.</p></body>')
    tobe = _html_blocks('<body><p>Leggi le <a href="https://example.invalid/b">condizioni</a> ora.</p></body>')
    result = compare_docs(target, tobe)
    assert _summary(result) == [("cambiato", "link")]
    diff = result.diffs[0]
    assert diff.detail == "href: https://example.invalid/a → https://example.invalid/b"
    assert (diff.left_text, diff.right_text) == ("https://example.invalid/a", "https://example.invalid/b")
    assert diff.anchor.klass == "link" and diff.anchor.target_text == "href: https://example.invalid/a"
    assert [w.text for w in diff.left] == ["Leggi", "le", "condizioni", "ora."]
    assert counts(diff, "tollerante") and counts(diff, "stretto") and not counts(diff, "solo_testo")


def test_tracking_parameters_are_dropped_only_with_the_rule():
    from qtrequestory.officina.compare import urls

    target = _html_blocks('<body><p><a href="https://example.invalid/p?id=1">Vai</a></p></body>')
    tobe = _html_blocks('<body><p><a href="https://example.invalid/p?id=1&utm_source=x">Vai</a></p></body>')
    assert _summary(compare_docs(target, tobe)) == [("cambiato", "link")]
    assert compare_docs(target, tobe, link_drop=urls.tracking_drop).diffs == ()


def test_an_image_only_block_gone_is_a_link_diff_and_anchors_stay_unique():
    target = _html_blocks('<body><p>Testo uguale</p><p><img src="https://example.invalid/l.png" alt="Logo"></p>'
                          '<p>Fine uguale</p></body>')
    tobe = _html_blocks('<body><p>Testo uguale</p><p>Fine uguale</p></body>')
    result = compare_docs(target, tobe)
    assert [(d.op, d.klass, d.detail) for d in result.diffs] == [
        ("cambiato", "link", "src: https://example.invalid/l.png → (assente)"),
        ("cambiato", "link", "alt: Logo → (assente)")]
    assert len({d.anchor for d in result.diffs}) == 2
    assert [d.id for d in result.diffs] == [1, 2]


