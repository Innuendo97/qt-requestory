def test_identical_documents_have_no_difference(pdfs: Path):
    result = compare_docs(_pdf(pdfs, "a.pdf", BASE), _pdf(pdfs, "b.pdf", BASE))
    assert result.diffs == () and result.note == ""
    assert result.left_has_text and result.right_has_text
    assert (result.left_pages, result.right_pages) == (1, 1)


def test_one_changed_letter_is_one_cambiato_with_spans_on_the_letter(pdfs: Path):
    target = _pdf(pdfs, "t.pdf", BASE)
    changed = _pdf(pdfs, "g.pdf", [BASE[0], BASE[1].replace("dodici", "dodoci"), BASE[2]])
    result = compare_docs(target, changed)
    assert _summary(result) == [("cambiato", "testo")]
    diff = result.diffs[0]
    assert diff.id == 1
    assert (diff.left_text, diff.right_text) == ("dodici", "dodoci")
    assert (diff.left_spans, diff.right_spans) == (((3, 4),), ((3, 4),))
    assert diff.left == tuple(w for w in target.words if w.text == "dodici")
    assert diff.anchor.target_text == "dodici"
    assert diff.anchor.context == "resta fisso per mesi. Le comunicazioni"


def test_text_reflowed_onto_the_next_page_is_no_difference(pdfs: Path):
    paragraphs = [pdfgen.lorem(110, seed=n) for n in range(7)]
    target = _pdf(pdfs, "t.pdf", paragraphs, font_pt=11)
    reflowed = _pdf(pdfs, "g.pdf", paragraphs, font_pt=11, width_mm=150)
    assert len(target.page_sizes) == len(reflowed.page_sizes) == 2, "same page count"
    first_on_2 = [w.text for w in reflowed.words if w.page == 1][0]
    assert next(w.page for w in target.words if w.text == first_on_2) == 0, "the fixture must really reflow"
    result = compare_docs(target, reflowed)
    assert result.diffs == (), _summary(result)


def test_a_filled_sure_slot_is_one_variable_and_nothing_counts(pdfs: Path):
    target = _html(pdfs, "t.pdf", "<p>Località ..........</p><p>Firma del cliente</p>")
    filled = _html(pdfs, "g.pdf", "<p>Località Springfield</p><p>Firma del cliente</p>")
