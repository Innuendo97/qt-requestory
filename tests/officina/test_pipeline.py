@pytest.mark.parametrize("layout", ["paragraphs", "one_block"])
def test_repeated_slot_rows_are_all_variables(pdfs: Path, layout: str):
    """Review Focus 1: ten identical form rows, every value a variable."""
    intro, outro = pdfgen.lorem(40, seed=1), pdfgen.lorem(30, seed=2)
    target = _pdf(pdfs, "t.pdf", [intro] + [ROW] * 10 + [outro])
    rows = [f"Nome Anna{k} Cognome Neri{k}" for k in range(10)]
    if layout == "paragraphs":
        generated = _pdf(pdfs, "g.pdf", [intro] + rows + [outro])
    else:  # consecutive filled rows at normal pitch: ONE generated block
        generated = _html(pdfs, "g.pdf", f"<p>{intro}</p><p>{'<br>'.join(rows)}</p><p>{outro}</p>")
    result = compare_docs(target, generated)
    assert _summary(result) == [("cambiato", "variabile")] * 20
    assert [d.right_text for d in result.diffs] == [v for k in range(10) for v in (f"Anna{k}", f"Neri{k}")]
    assert len({d.anchor for d in result.diffs}) == 20
    assert result.slots_found == 20


