def _pdf(pdfs: Path, name: str, paragraphs: list[str], **kw) -> DocText:
    return extract(pdfgen.paragraphs_pdf(pdfs / name, paragraphs, **kw))


def _html(pdfs: Path, name: str, html: str, **kw) -> DocText:
    return extract(pdfgen.html_pdf(pdfs / name, html, **kw))


def _summary(result: Comparison) -> list[tuple[str, str]]:
    return [(d.op, d.klass) for d in result.diffs]


def _counting(result: Comparison, profile: str = "tollerante") -> list:
    return [d for d in result.diffs if counts(d, profile)]  # type: ignore[arg-type]


