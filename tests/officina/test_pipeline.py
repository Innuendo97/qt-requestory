def test_a_change_carries_up_to_five_target_words_of_context_on_each_side():
    text = "Il prezzo della componente servizio resta fisso per dodici mesi dalla firma."
    result = compare_docs(_doc(text), _doc(text.replace("dodici", "sei")))
    diff = result.diffs[0]
    assert (diff.left_text, diff.right_text) == ("dodici", "sei")
    assert diff.context_before == "componente servizio resta fisso per"
    assert diff.context_after == "mesi dalla firma."


def test_an_insertion_is_framed_by_the_target_words_around_it():
    result = compare_docs(_doc("Uno due tre quattro cinque sei."), _doc("Uno due tre NUOVO quattro cinque sei."))
    diff = result.diffs[0]
    assert diff.op == "in_piu"
    assert (diff.context_before, diff.context_after) == ("Uno due tre", "quattro cinque sei.")


def test_context_stays_in_the_block_and_falls_back_to_the_neighbours_for_a_whole_block():
    intro, price = "Premessa del contratto di prova tra le parti.", "Il prezzo resta fisso per dodici mesi."
    changed = compare_docs(_doc(intro, price), _doc(intro, price.replace("Il", "Lo", 1))).diffs[0]
    assert changed.context_before == "di prova tra le parti."  # starts its block: the neighbour's words
    assert changed.context_after == "prezzo resta fisso per dodici"
    section = next(d for d in compare_docs(_doc(intro, SECTION, price), _doc(intro, price)).diffs
                   if d.op == "sezione_assente")
    assert section.context_before == "di prova tra le parti."
    assert section.context_after == "Il prezzo resta fisso per"


