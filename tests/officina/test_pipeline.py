    assert _summary(result) == expected
    section = next(d for d in result.diffs if d.op == "sezione_assente")
    assert section.left_text == SECTION and section.detail == "2 righe"
    other = next(d for d in result.diffs if d.op != "sezione_assente")
    assert other.left_text in ("Il", "") and other.right_text in ("Lo", "Aggiunta")


