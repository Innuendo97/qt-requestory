def test_words_have_boxes_in_points_from_the_top_left(pdfs: Path):
    path = pdfgen.paragraphs_pdf(pdfs / "a.pdf", ["Alfa beta gamma"] + ["riempitivo"] * 3)
    doc = extract(path)
    assert isinstance(doc, DocText)
    assert doc.has_text
    assert [w.text for w in doc.words[:3]] == ["Alfa", "beta", "gamma"]
    w, h = doc.page_sizes[0]
    assert w == pytest.approx(595, abs=1) and h == pytest.approx(842, abs=1)
    first = doc.words[0]
    assert isinstance(first, Word) and first.page == 0
    assert 0 <= first.x0 < first.x1 <= w
    assert 0 <= first.y0 < first.y1 < h / 4, "the first line sits near the TOP of the page"
    beta = doc.words[1]
    assert beta.x0 > first.x1, "words on one line go left to right"
    assert beta.y0 == pytest.approx(first.y0, abs=2)


def test_reading_order_is_top_to_bottom_then_left_to_right(pdfs: Path):
    path = pdfgen.paragraphs_pdf(pdfs / "a.pdf", ["uno due", "tre quattro", "cinque sei"])
    words = extract(path).words
    assert [w.text for w in words] == ["uno", "due", "tre", "quattro", "cinque", "sei"]
    assert words[2].y0 > words[0].y1


def test_punctuation_stays_attached_to_its_word(pdfs: Path):
    path = pdfgen.paragraphs_pdf(pdfs / "a.pdf", ["Primo, secondo; terzo."])
    assert [w.text for w in extract(path).words] == ["Primo,", "secondo;", "terzo."]


def test_line_end_hyphen_is_extracted_as_a_hyphen(pdfs: Path):
    path = pdfgen.html_pdf(pdfs / "a.pdf", "<p>Il para-<br>grafo continua</p>")
    assert [w.text for w in extract(path).words] == ["Il", "para-", "grafo", "continua"]


def test_pages_are_numbered_and_sized(pdfs: Path):
    text = pdfgen.lorem(1500)
    doc = extract(pdfgen.paragraphs_pdf(pdfs / "a.pdf", [text]))
    assert len(doc.page_sizes) >= 2
    assert doc.words[0].page == 0 and doc.words[-1].page == len(doc.page_sizes) - 1
    pages = [w.page for w in doc.words]
    assert pages == sorted(pages)
    assert " ".join(w.text for w in doc.words) == text


def test_image_only_pdf_has_no_text(pdfs: Path):
    doc = extract(pdfgen.image_only_pdf(pdfs / "scan.pdf", pages=2))
    assert doc.has_text is False
    assert doc.words == []
    assert len(doc.page_sizes) == 2


